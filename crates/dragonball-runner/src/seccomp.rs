use seccompiler::{BpfProgram, SeccompAction, SeccompFilter};

/// Install on the single runner main thread before VMM construction. All
/// subsequently spawned API/device/vCPU threads inherit the same filter.
pub fn install_m0_filter() -> anyhow::Result<()> {
    let syscalls = [
        // Rust/glibc allocation, threads, clocks, signals and process identity.
        libc::SYS_brk,
        libc::SYS_mmap,
        libc::SYS_mprotect,
        libc::SYS_munmap,
        libc::SYS_mremap,
        libc::SYS_madvise,
        libc::SYS_mincore,
        libc::SYS_clone,
        libc::SYS_clone3,
        libc::SYS_futex,
        // Kernel restart of poll/futex/nanosleep after stop and continue.
        libc::SYS_restart_syscall,
        libc::SYS_rseq,
        libc::SYS_set_robust_list,
        libc::SYS_sched_getaffinity,
        libc::SYS_sched_yield,
        libc::SYS_rt_sigaction,
        libc::SYS_rt_sigprocmask,
        libc::SYS_rt_sigreturn,
        libc::SYS_sigaltstack,
        libc::SYS_tgkill,
        libc::SYS_getpid,
        libc::SYS_gettid,
        libc::SYS_getppid,
        libc::SYS_getuid,
        libc::SYS_geteuid,
        libc::SYS_getgid,
        libc::SYS_getegid,
        libc::SYS_prctl,
        libc::SYS_prlimit64,
        libc::SYS_clock_gettime,
        libc::SYS_clock_nanosleep,
        libc::SYS_nanosleep,
        libc::SYS_gettimeofday,
        libc::SYS_getrandom,
        libc::SYS_exit,
        libc::SYS_exit_group,
        // Kernel/tools/block files, RAM/snapshot files and KVM/TAP ioctls.
        libc::SYS_open,
        libc::SYS_openat,
        libc::SYS_close,
        libc::SYS_close_range,
        libc::SYS_read,
        libc::SYS_write,
        libc::SYS_readv,
        libc::SYS_writev,
        libc::SYS_pread64,
        libc::SYS_pwrite64,
        libc::SYS_preadv,
        libc::SYS_pwritev,
        libc::SYS_lseek,
        libc::SYS_fstat,
        libc::SYS_stat,
        libc::SYS_newfstatat,
        libc::SYS_statx,
        libc::SYS_readlink,
        libc::SYS_readlinkat,
        libc::SYS_getdents64,
        libc::SYS_fcntl,
        libc::SYS_ioctl,
        libc::SYS_dup,
        libc::SYS_dup3,
        libc::SYS_fsync,
        libc::SYS_fdatasync,
        libc::SYS_ftruncate,
        libc::SYS_fallocate,
        libc::SYS_memfd_create,
        libc::SYS_unlink,
        libc::SYS_unlinkat,
        libc::SYS_chmod,
        // MMIO RawBlock chooses io_uring, or native Linux AIO when unavailable.
        libc::SYS_io_uring_setup,
        libc::SYS_io_uring_register,
        libc::SYS_io_uring_enter,
        libc::SYS_io_setup,
        libc::SYS_io_destroy,
        libc::SYS_io_submit,
        libc::SYS_io_getevents,
        libc::SYS_io_cancel,
        // User-mode net and private UDS control; no vhost/VFIO/mount/setns/exec.
        libc::SYS_socket,
        libc::SYS_socketpair,
        libc::SYS_bind,
        libc::SYS_listen,
        libc::SYS_accept4,
        libc::SYS_getsockopt,
        libc::SYS_setsockopt,
        libc::SYS_getsockname,
        libc::SYS_getpeername,
        libc::SYS_shutdown,
        libc::SYS_sendto,
        libc::SYS_recvfrom,
        libc::SYS_sendmsg,
        libc::SYS_recvmsg,
        libc::SYS_poll,
        libc::SYS_ppoll,
        libc::SYS_epoll_create1,
        libc::SYS_epoll_ctl,
        libc::SYS_epoll_wait,
        libc::SYS_epoll_pwait,
        libc::SYS_eventfd2,
        libc::SYS_timerfd_create,
        libc::SYS_timerfd_settime,
    ];
    let filter = SeccompFilter::new(
        syscalls.into_iter().map(|n| (n, vec![])).collect(),
        SeccompAction::KillProcess,
        SeccompAction::Allow,
        std::env::consts::ARCH.try_into()?,
    )?;
    let program: BpfProgram = filter.try_into()?;
    seccompiler::apply_filter(&program)?;
    Ok(())
}
